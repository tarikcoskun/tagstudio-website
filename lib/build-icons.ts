import crypto from "node:crypto"
import fs from "node:fs/promises"
import path from "node:path"
import { $ } from "execa"
import { glob } from "glob"
import { optimize } from "svgo"

const cwd = process.cwd()
const iconsDir = path.join(cwd, "assets", "icons")
const hashPath = path.join(cwd, "assets", ".icon-sprite.hash")
const typesPath = path.join(cwd, "src", "types", "icon-list.ts")
const spritePath = path.join(cwd, "public", "sprite.svg")

const isForced = process.argv.includes("--force")
const isVerbose = !process.argv.includes("--silent")

const colors = {
	red: "\x1b[31m",
	green: "\x1b[32m",
	yellow: "\x1b[33m",
	blue: "\x1b[34m",
	reset: "\x1b[0m",
}

const log = {
	success: (msg: string) => console.log(`${colors.green}✔${colors.reset} ${msg}`),
	info: (msg: string) => isVerbose && console.log(`${colors.blue}ℹ${colors.reset} ${msg}`),
	warn: (msg: string) => console.warn(`${colors.yellow}⚠${colors.reset} ${msg}`),
	error: (msg: string) => console.error(`${colors.red}✖${colors.reset} ${msg}`),
}

const hash = (content: string) => crypto.createHash("sha1").update(content).digest("hex")
const readFile = (path: string) => fs.readFile(path, "utf8").catch(() => "")

const writeFileIfChanged = async (filePath: string, newContent: string) => {
	const currentContent = await readFile(filePath)
	if (currentContent === newContent) return false

	await fs.writeFile(filePath, newContent, "utf8")
	await $`prettier --write --ignore-unknown ${filePath}`.catch(() => {
		log.warn(`Prettier not found, skipping formatting for ${filePath}`)
	})

	return true
}

const shouldPreserveColors = async (svgContent: string, libraryDir: string) => {
	if (svgContent.includes("<!-- preserve colors -->")) return true

	try {
		await fs.access(path.join(libraryDir, ".stroke-icons"))
		return true
	} catch {
		return false
	}
}

const optimizeSvg = (content: string, preserveColors = false) => {
	const { data } = optimize(content, {
		multipass: true,
		plugins: [
			"removeDimensions",
			"removeTitle",
			"removeDesc",
			"removeXMLNS",
			{ name: "removeAttrs", params: { attrs: "(class|data.*)" } },
			{ name: "convertColors", params: { currentColor: !preserveColors } },
		],
	})

	return data
}

const getIcons = async () => {
	const libraries = await fs.readdir(iconsDir).catch(() => [])
	const icons = []

	for (const library of libraries) {
		const libraryDir = path.join(iconsDir, library)
		const svgFiles = glob.sync("**/*.svg", { cwd: libraryDir }).sort()

		if (svgFiles.length === 0) {
			log.warn(`No SVG files found in ${library}`)
			continue
		}

		for (const file of svgFiles) {
			const filePath = path.join(libraryDir, file)
			const iconName = `${library}:${file.replace(/\.svg$/, "").replaceAll("\\\\", "/")}`
			icons.push({ filePath, iconName, library, libraryDir })
		}
	}

	return icons
}

type Icons = Awaited<ReturnType<typeof getIcons>>

const generateSprite = async (icons: Icons) => {
	const symbols = []

	for (const icon of icons) {
		try {
			const svgContent = await fs.readFile(icon.filePath, "utf8")
			const preserveColors = await shouldPreserveColors(svgContent, icon.libraryDir)

			const content = svgContent.match(/<svg[^>]*>([\s\S]*?)<\/svg>/i)?.[1]
			const viewBox = svgContent.match(/viewBox="([^"]*)"/i)?.[1]

			if (!content || !viewBox) {
				log.warn(`Invalid SVG: ${icon.iconName}`)
				continue
			}

			const optimized = optimizeSvg(content, preserveColors)
			symbols.push(`\t<symbol viewBox="${viewBox}" id="${icon.iconName}">${optimized}</symbol>`)

			if (isVerbose) console.log(`• ${icon.iconName}`)
		} catch (err) {
			log.warn(`Failed to process ${icon.iconName}: ${err}`)
		}
	}

	return [
		`<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="0" height="0">`,
		"<defs>",
		...symbols,
		"</defs>",
		"</svg>",
		"",
	].join("\n")
}

const generateTypes = (icons: Icons) => `
// This file is generated by bun run build:icons

export const iconList = [
	${icons.map((icon) => JSON.stringify(icon.iconName)).join(",\n\t")}
] as const

export type IconList = typeof iconList[number]
`

const main = async () => {
	const icons = await getIcons()
	if (icons.length === 0) {
		log.info("No icons found")
		return
	}

	const iconData = icons.map((i) => i.filePath + i.iconName).join("|")
	const currentHash = hash(iconData)
	const lastHash = await readFile(hashPath)

	if (!isForced && currentHash === lastHash) {
		log.info("Icons are up to date")
		return
	}

	const sprite = await generateSprite(icons)
	const spriteChanged = await writeFileIfChanged(spritePath, sprite)

	const types = generateTypes(icons)
	const typesChanged = await writeFileIfChanged(typesPath, types)

	await fs.writeFile(hashPath, currentHash, "utf8")

	if (spriteChanged) log.info(`Sprite saved to ${path.relative(process.cwd(), spritePath)}`)
	if (typesChanged) log.info(`Types saved to ${path.relative(process.cwd(), typesPath)}`)

	log.success(`Generated ${icons.length} icons`)
}

main()
